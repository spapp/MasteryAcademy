#!/usr/bin/env python3
"""Generates everything derived from spec/api.json. Standard library only.

  contracts/openapi.json                                   OpenAPI 3.0.3
  backend/app/generated/operations.py                      route manifest the API is checked against
  ios/MasteryAcademy/Core/Networking/APIOperations.gen.swift   typed operations for the app

Usage: python3 tools/specgen/gen.py [--check]   (--check fails if generated files are out of date)
"""
import json, os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SPEC = json.load(open(os.path.join(ROOT, "spec/api.json")))
BASE = SPEC["info"]["basePath"]
PRIM = {"string": {"type": "string"}, "int": {"type": "integer"}, "bool": {"type": "boolean"},
        "uuid": {"type": "string", "format": "uuid"}, "datetime": {"type": "string", "format": "date-time"}}


def schema_ref(t):
    nullable = t.endswith("?")
    t = t.rstrip("?")
    if t.endswith("[]"):
        s = {"type": "array", "items": schema_ref(t[:-2])}
    elif t in PRIM:
        s = dict(PRIM[t])
    elif t in SPEC["enums"]:
        s = {"type": "string", "enum": SPEC["enums"][t]}
    else:
        s = {"$ref": f"#/components/schemas/{t}"}
    if nullable and "$ref" not in s:
        s["nullable"] = True
    return s


def openapi():
    comps = {}
    for name, fields in SPEC["schemas"].items():
        if "_opaque" in fields:
            comps[name] = {"type": "object", "description": fields["_opaque"], "additionalProperties": True}
            continue
        comps[name] = {"type": "object", "properties": {k: schema_ref(v) for k, v in fields.items()},
                       "required": [k for k, v in fields.items() if not v.endswith("?")]}
    comps["Error"] = {"type": "object", "required": ["error"], "properties": {"error": {"type": "object", "required": ["code", "message", "requestId"], "properties": {
        "code": {"type": "string", "enum": SPEC["enums"]["ErrorCode"]}, "message": {"type": "string"}, "requestId": {"type": "string"},
        "fields": {"type": "object", "additionalProperties": {"type": "string"}}}}}}
    paths = {}
    for op in SPEC["operations"]:
        status = str(op.get("status", 200))
        o = {"operationId": op["id"], "summary": op["summary"], "tags": [op["module"]], "x-rate-tier": op["tier"]}
        params = [{"name": p, "in": "path", "required": True, "schema": {"type": "string"}} for p in re.findall(r"\{(\w+)\}", op["path"])]
        for q, t in op.get("query", {}).items():
            params.append({"name": q, "in": "query", "required": not t.endswith("?"), "schema": schema_ref(t)})
        if params:
            o["parameters"] = params
        if op["auth"] == "appkey":
            o["security"] = [{"appKey": []}]
        elif op["auth"] != "public":
            o["security"] = [{"bearer": []}]
        if "body" in op:
            o["requestBody"] = {"required": True, "content": {"application/json": {"schema": schema_ref(op["body"])}}}
        if "response" in op:
            env = {"type": "object", "required": ["data"], "properties": {"data": schema_ref(op["response"])}}
            if op.get("paged"):
                env["required"].append("page")
                env["properties"]["page"] = {"type": "object", "required": ["cursor"], "properties": {"nextCursor": {"type": "integer", "nullable": True}, "cursor": {"type": "integer"}}}
            o["responses"] = {status: {"description": "OK", "content": {"application/json": {"schema": env}}}}
        else:
            o["responses"] = {status: {"description": "No content"}}
        if op.get("etag"):
            o["responses"]["304"] = {"description": "Not modified"}
        o["responses"]["default"] = {"description": "Error", "content": {"application/json": {"schema": {"$ref": "#/components/schemas/Error"}}}}
        paths.setdefault(BASE + op["path"], {})[op["method"].lower()] = o
    return json.dumps({"openapi": "3.0.3", "info": {"title": SPEC["info"]["title"], "version": SPEC["info"]["version"]}, "paths": paths,
                       "components": {"schemas": comps, "securitySchemes": {"bearer": {"type": "http", "scheme": "bearer", "bearerFormat": "JWT"},
                                                                      "appKey": {"type": "apiKey", "in": "header", "name": "X-App-Key"}}}}, indent=1) + "\n"


def py_manifest():
    lines = ['"""GENERATED by tools/specgen/gen.py from spec/api.json. Do not edit."""', "", f'BASE_PATH = "{BASE}"', "", "OPERATIONS = {"]
    for op in SPEC["operations"]:
        lines.append(f'    "{op["id"]}": {{"method": "{op["method"]}", "path": "{op["path"]}", "auth": "{op["auth"]}", "tier": "{op["tier"]}", "status": {op.get("status", 200)}, "module": "{op["module"]}"}},')
    lines += ["}", "", f'PROGRESS_KINDS = {tuple(SPEC["enums"]["ProgressKind"])!r}', f'ERROR_CODES = {tuple(SPEC["enums"]["ErrorCode"])!r}', ""]
    return "\n".join(lines)


def swift_ops():
    out = ["// GENERATED by tools/specgen/gen.py from spec/api.json. Do not edit.", "import Foundation", "",
           "struct APIOperation: Sendable {", "    let id: String", "    let method: String", "    let path: String", "    let requiresAuth: Bool", "",
           f'    static let basePath = "{BASE}"', ""]
    for op in SPEC["operations"]:
        params = re.findall(r"\{(\w+)\}", op["path"])
        auth = "true" if op["auth"] == "user" else "false"
        out.append(f'    /// {op["summary"]}')
        if params:
            sig = ", ".join(f"{p}: String" for p in params)
            path = re.sub(r"\{(\w+)\}", r"\\(\1)", op["path"])
            out.append(f'    static func {op["id"]}({sig}) -> APIOperation {{ APIOperation(id: "{op["id"]}", method: "{op["method"]}", path: "{path}", requiresAuth: {auth}) }}')
        else:
            out.append(f'    static let {op["id"]} = APIOperation(id: "{op["id"]}", method: "{op["method"]}", path: "{op["path"]}", requiresAuth: {auth})')
    out += ["}", "", "enum ProgressKind: String, Codable, Sendable, CaseIterable {"]
    out += [f"    case {k}" for k in SPEC["enums"]["ProgressKind"]]
    out += ["}", ""]
    return "\n".join(out)


TARGETS = {
    "contracts/openapi.json": openapi,
    "backend/app/generated/operations.py": py_manifest,
    "ios/MasteryAcademy/Core/Networking/APIOperations.gen.swift": swift_ops,
}

if __name__ == "__main__":
    check = "--check" in sys.argv
    stale = []
    for rel, fn in TARGETS.items():
        path = os.path.join(ROOT, rel)
        text = fn()
        if check:
            if not os.path.exists(path) or open(path).read() != text:
                stale.append(rel)
            continue
        os.makedirs(os.path.dirname(path), exist_ok=True)
        open(path, "w").write(text)
        print("wrote", rel)
    if stale:
        sys.exit("out of date, run tools/specgen/gen.py: " + ", ".join(stale))
    print(f"{len(SPEC['operations'])} operations, {len(SPEC['schemas'])} schemas")
